type Codec struct {
	topic string
	ser   *jsonschema.Serializer
	deser *jsonschema.Deserializer
}

func NewCodec(topic, srURL string) (*Codec, error) {
	client, err := schemaregistry.NewClient(schemaregistry.NewConfig(srURL))
	if err != nil {
		return nil, fmt.Errorf("schema registry client: %w", err)
	}

	subject := topic + "-value"
	_, err = client.Register(subject, schemaregistry.SchemaInfo{
		Schema:     productPayloadSchemaDraft7,
		SchemaType: "JSON",
	}, false)
	if err != nil {
		return nil, fmt.Errorf("register schema for %s: %w", subject, err)
	}

	serCfg := jsonschema.NewSerializerConfig()
	serCfg.AutoRegisterSchemas = false
	serCfg.UseLatestVersion = true
	ser, err := jsonschema.NewSerializer(client, serde.ValueSerde, serCfg)
	if err != nil {
		return nil, fmt.Errorf("jsonschema serializer: %w", err)
	}

	deser, err := jsonschema.NewDeserializer(client, serde.ValueSerde, jsonschema.NewDeserializerConfig())
	if err != nil {
		return nil, fmt.Errorf("jsonschema deserializer: %w", err)
	}

	return &Codec{topic: topic, ser: ser, deser: deser}, nil
}

func (c *Codec) Encode(value any) ([]byte, error) {
	p, ok := value.(*Product)
	if !ok {
		return nil, fmt.Errorf("тип должен быть *Product, получен %T", value)
	}

	payload, err := productToPayload(p)
	if err != nil {
		return nil, fmt.Errorf("encode payload: %w", err)
	}

	return c.ser.Serialize(c.topic, &payload)
}

func (c *Codec) Decode(data []byte) (any, error) {
	var payload ProductPayload
	if err := c.deser.DeserializeInto(c.topic, data, &payload); err != nil {
		return nil, fmt.Errorf("deserialize: %w", err)
	}

	return payloadToProduct(payload)
}
